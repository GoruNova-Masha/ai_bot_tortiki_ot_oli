_BENTO_DECOR_FILENAME = "Правила декорирования бенто-тортов.md"


def _read_text(path: Path) -> str:
    if path.is_file():
        return path.read_text(encoding="utf-8")
    return ""


def _find_prompt_file(brief_path: Path, filename: str) -> Path:
    for candidate in (
        brief_path.parent / filename,
        brief_path.parent.parent / filename,
    ):
        if candidate.is_file():
            return candidate
    return brief_path.parent / filename


def _load_prompt_section(brief_path: Path, filename: str, fallback: str) -> str:
    content = _read_text(_find_prompt_file(brief_path, filename)).strip()
    return content or fallback


